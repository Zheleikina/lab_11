// Лабораторна робота №11, частина 5, завдання 2.
// Захоплення змінних у лямбда-виразах: за значенням і за посиланням.
//
// РЕЗУЛЬТАТ ОРИГІНАЛЬНОЇ ПРОГРАМИ: компілюється; виводить   6 30
//
// ПОЯСНЕННЯ.
//  * [k] (за значенням). У момент створення лямбди в неї кладеться КОПІЯ k
//    (тоді k == 2). Далі лямбда працює зі своєю копією, і k = 10 її не чіпає:
//    byValue(3) = 3 * 2 = 6.
//  * [&k] (за посиланням). Лямбда зберігає посилання на саму змінну k, а не
//    її значення. Тому під час виклику вона читає актуальне k == 10:
//    byRef(3) = 3 * 10 = 30.
//  Різниця в тому, ЩО зберігається: копія (знімок на момент створення) чи
//  посилання (живий зв'язок із зовнішньою змінною).
//
// Помилки тут немає, тож "виправляти" нічого не треба. Нижче код
// розширено перевірками, які це доводять, і показано небезпеку захоплення за
// посиланням: лямбда з [&] не можна використовувати, коли змінна вже знищена.

#include <iostream>

int main() {
    int k = 2;

    auto byValue = [k](int x) { return x * k; };
    auto byRef = [&k](int x) { return x * k; };

    std::cout << "k = " << k << ": " << byValue(3) << ' ' << byRef(3) << '\n';

    k = 10;
    std::cout << "k = " << k << ": " << byValue(3) << ' ' << byRef(3) << '\n';

    // Захоплена за значенням копія за замовчуванням незмінна, змінити її
    // можна лише з mutable - і то лише всередині самої лямбди:
    auto counter = [n = 0]() mutable { return ++n; };
    std::cout << "mutable-лічильник: " << counter() << ' ' << counter() << ' '
              << counter() << '\n';
}
